async function login(){

  const username =
    document
      .getElementById(
        'username'
      )
      .value;

  const password =
    document
      .getElementById(
        'password'
      )
      .value;

  try{

    const data =
      await api(
        '/api/auth/login',
        {
          method:'POST',
          body:
            JSON.stringify({
              username,
              password
            })
        }
      );

    token =
      data.token;

    localStorage.setItem(
      TOKEN_KEY,
      token
    );

    await startApp();

  }catch(error){

    toast(
      error.message
    );
  }
}

