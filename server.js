function hashRecoveryCode(code) {
  return crypto
    .createHash('sha256')
    .update(
      String(code || '')
        .trim()
        .toUpperCase()
    )
    .digest('hex');
}

function recoveryCodeMatches(
  user,
  suppliedCode
) {
  if (
    !user.recoveryCodeHash ||
    !suppliedCode
  ) {
    return false;
  }

  const a = Buffer.from(
    user.recoveryCodeHash,
    'hex'
  );

  const b = Buffer.from(
    hashRecoveryCode(suppliedCode),
    'hex'
  );

  return (
    a.length === b.length &&
    crypto.timingSafeEqual(a, b)
  );
}

function createToken(user) {
  return jwt.sign(
    {
      userId: user.id,
      username: user.username
    },
    JWT_SECRET,
    {
      expiresIn: '30d'
    }
  );
}

function auth(req, res, next) {
  const header =
    req.headers.authorization || '';

  if (!header.startsWith('Bearer ')) {
    return sendError(
      res,
      401,
      'Требуется авторизация'
    );
  }

  try {
    const decoded = jwt.verify(
      header.slice(7),
      JWT_SECRET
    );

    const user = db.users.find(
      u => u.id === decoded.userId
    );

    if (!user) {
      return sendError(
        res,
        401,
        'Пользователь не найден'
      );
    }

    req.user = user;

    next();
  } catch {
    return sendError(
      res,
      401,
      'Недействительная сессия'
    );
  }
}

