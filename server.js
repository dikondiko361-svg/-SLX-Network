function drawChart(
  candles
){

  const canvas =
    document.getElementById(
      'chart'
    );

  const rect =
    canvas.getBoundingClientRect();

  const dpr =
    window.devicePixelRatio ||
    1;

  canvas.width =
    rect.width * dpr;

  canvas.height =
    rect.height * dpr;

  const ctx =
    canvas.getContext(
      '2d'
    );

  ctx.scale(
    dpr,
    dpr
  );

  const width =
    rect.width;

  const height =
    rect.height;

  ctx.fillStyle =
    '#090e18';

  ctx.fillRect(
    0,
    0,
    width,
    height
  );

  if (!candles.length){
    return;
  }

  const prices =
    candles.flatMap(
      c => [
        c.high,
        c.low
      ]
    );

  const max =
    Math.max(...prices);

  const min =
    Math.min(...prices);

  const range =
    max - min ||
    0.000001;

  const left =
    12;

  const right =
    width - 12;

  const top =
    15;

  const bottom =
    height - 20;

  const step =
    (right - left) /
    candles.length;

  /* grid */

  ctx.strokeStyle =
    '#182131';

  ctx.lineWidth =
    1;

  for (
    let i = 1;
    i < 5;
    i++
  ){

    const y =
      top +
      (
        (bottom - top) /
        5
      ) * i;

    ctx.beginPath();

    ctx.moveTo(
      left,
      y
    );

    ctx.lineTo(
      right,
      y
    );

    ctx.stroke();
  }

  candles.forEach(
    (c, i) => {

      const x =
        left +
        i * step +
        step / 2;

      const yOpen =
        bottom -
        (
          (c.open - min) /
          range
        ) *
        (bottom - top);

      const yClose =
        bottom -
        (
          (c.close - min) /
          range
        ) *
        (bottom - top);

      const yHigh =
        bottom -
        (
          (c.high - min) /
          range
        ) *
        (bottom - top);

      const yLow =
        bottom -
        (
          (c.low - min) /
          range
        ) *
        (bottom - top);

      const rising =
        c.close >= c.open;

      ctx.strokeStyle =
        rising
          ? '#31d69b'
          : '#ff617d';

      ctx.fillStyle =
        rising
          ? '#31d69b'
          : '#ff617d';

      ctx.lineWidth =
        1;

      ctx.beginPath();

      ctx.moveTo(
        x,
        yHigh
      );

      ctx.lineTo(
        x,
        yLow
      );

      ctx.stroke();

      const bodyTop =
        Math.min(
          yOpen,
          yClose
        );

      const bodyHeight =
        Math.max(
          2,
          Math.abs(
            yClose -
            yOpen
          )
        );

      ctx.fillRect(
        x -
        Math.max(
          2,
          step * .3
        ) / 2,

        bodyTop,

        Math.max(
          2,
          step * .3
        ),

        bodyHeight
      );

    }
  );

  ctx.fillStyle =
    '#8390a7';

  ctx.font =
    '11px Arial';

  ctx.fillText(
    max.toFixed(4),
    8,
    12
  );

  ctx.fillText(
    min.toFixed(4),
    8,
    height - 5
  );
}

