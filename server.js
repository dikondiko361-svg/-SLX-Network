async function api(
  url,
  options = {}
){

  const headers = {
    'Content-Type':
      'application/json',
    ...(options.headers || {})
  };

  if (token){
    headers.Authorization =
      'Bearer ' + token;
  }

  const response =
    await fetch(
      url,
      {
        ...options,
        headers
      }
    );

  let data;

  try{
    data =
      await response.json();
  }catch{
    data = {};
  }

  if (
    !response.ok ||
    data.ok === false
  ){

    throw new Error(
      data.message ||
      data.error ||
      'Ошибка сервера'
    );
  }

  return data;
}

