function calculateBlockHash(block) {
  return crypto
    .createHash('sha256')
    .update(
      JSON.stringify({
        index: block.index,
        previousHash:
          block.previousHash,
        transactions:
          block.transactions,
        timestamp:
          block.timestamp
      })
    )
    .digest('hex');
}

function createBlock(transaction) {
  const previous =
    db.blocks[
      db.blocks.length - 1
    ];

  const index =
    db.blocks.length;

  const block = {
    index,

    height:
      index + 1,

    block_index:
      index,

    previousHash:
      previous
        ? previous.hash
        : '0'.repeat(64),

    transactions: [
      transaction
    ],

    transaction_count:
      1,

    timestamp:
      Date.now(),

    hash:
      ''
  };

  block.hash =
    calculateBlockHash(block);

  db.blocks.push(block);

  db.network.height =
    db.blocks.length;

  return block;
}

