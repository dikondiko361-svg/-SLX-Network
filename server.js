function createWalletForUser(
  userId,
  initial = false
) {
  let address;

  do {
    address =
      walletAddress();
  } while (
    getWalletByAddress(address)
  );

  const wallet = {
    id:
      id('WLT_').toUpperCase(),

    userId,

    address,

    balance:
      initial ? 100 : 0,

    createdAt:
      now()
  };

  db.wallets.push(wallet);

  if (initial) {
    db.network.totalSupply =
      round(
        db.network.totalSupply +
        wallet.balance
      );

    addTransaction({
      type: 'genesis',

      from:
        'SLX_GENESIS',

      to:
        wallet.address,

      amount:
        wallet.balance,

      fee:
        0,

      walletId:
        wallet.id,

      userId
    });
  }

  return wallet;
}

