app.post(
  '/api/send',
  auth,
  (req, res, next) => {
    try {
      const to =
        String(
          req.body?.to ||
          req.body?.toAddress ||
          req.body?.address ||
          ''
        )
        .trim()
        .toUpperCase();

      const amount =
        round(
          number(
            req.body?.amount
          )
        );

      const wallet =
        getWallet(
          req.user.id,
          req.body?.fromWalletId ||
          req.user.activeWalletId
        ) ||
        activeWalletFor(
          req.user
        );

      if (
        !/^SLXC[A-F0-9]{32}$/.test(
          to
        )
      ) {
        return sendError(
          res,
          400,
          'Неверный адрес SLX'
        );
      }

      if (
        amount <= 0
      ) {
        return sendError(
          res,
          400,
          'Сумма должна быть больше 0'
        );
      }

      if (!wallet) {
        return sendError(
          res,
          400,
          'Активный кошелёк не найден'
        );
      }

      const recipient =
        getWalletByAddress(to);

      if (!recipient) {
        return sendError(
          res,
          404,
          'Кошелёк получателя не найден в тестовой сети'
        );
      }

      if (
        recipient.id ===
          wallet.id ||
        recipient.userId ===
          wallet.userId
      ) {
        return sendError(
          res,
          400,
          'Для теста используй кошелёк другого пользователя'
        );
      }

      const total =
        round(
          amount +
          TRANSFER_FEE
        );

      if (
        wallet.balance + 1e-8 <
        total
      ) {
        return sendError(
          res,
          400,
          `Недостаточно SLX. Нужно ${total} SLX`
        );
      }

      wallet.balance =
        round(
          wallet.balance -
          total
        );

      recipient.balance =
        round(
          recipient.balance +
          amount
        );

      const tx =
        addTransaction({
          type:
            'transfer',

          from:
            wallet.address,

          to:
            recipient.address,

          amount,

          fee:
            TRANSFER_FEE,

          walletId:
            wallet.id,

          userId:
            req.user.id
        });

      createBlock(tx);

      saveDB();

      res.json({
        ok: true,
        transaction: tx,
        tx,
        fee:
          TRANSFER_FEE,
        balance:
          wallet.balance
      });
    } catch (error) {
      next(error);
    }
  }
);

