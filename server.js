function addTransaction(data) {
  const transactionTime = now();

  const payload = {
    ...data,
    time: Date.now(),
    nonce:
      crypto.randomBytes(8)
        .toString('hex')
  };

  const tx = {
    id: id('tx_'),

    hash:
      crypto
        .createHash('sha256')
        .update(JSON.stringify(payload))
        .digest('hex'),

    type:
      data.type || 'transfer',

    from:
      data.from || null,

    to:
      data.to || null,

    from_wallet:
      data.from || null,

    to_wallet:
      data.to || null,

    amount:
      round(data.amount || 0),

    fee:
      round(data.fee || 0),

    walletId:
      data.walletId || null,

    userId:
      data.userId || null,

    createdAt:
      transactionTime,

    created_at:
      transactionTime,

    timestamp:
      transactionTime,

    status:
      'confirmed'
  };

  db.transactions.push(tx);

  return tx;
}

function transactionsForWallet(wallet) {
  const address =
    String(wallet.address)
      .toUpperCase();

  return db.transactions
    .filter(tx =>
      String(tx.from || '')
        .toUpperCase() === address ||

      String(tx.to || '')
        .toUpperCase() === address ||

      String(tx.walletId || '') ===
        String(wallet.id)
    )
    .slice()
    .reverse();
}

