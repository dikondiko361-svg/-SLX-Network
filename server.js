function verifyChain() {
  for (
    let i = 0;
    i < db.blocks.length;
    i++
  ) {
    const block =
      db.blocks[i];

    const previous =
      i === 0
        ? '0'.repeat(64)
        : db.blocks[i - 1].hash;

    if (
      block.previousHash !==
      previous
    ) {
      return {
        valid: false,
        error:
          `Ошибка previousHash в блоке ${i}`
      };
    }

    if (
      block.hash !==
      calculateBlockHash(block)
    ) {
      return {
        valid: false,
        error:
          `Ошибка hash в блоке ${i}`
      };
    }
  }

  return {
    valid: true,
    error: null
  };
}

